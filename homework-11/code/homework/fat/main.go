package main

import (
	"log"
	"net/http"

	"clinic/homework/fat/delivery"
	"clinic/homework/fat/repository"
	"clinic/homework/fat/usecase"
)

func newMux() *http.ServeMux {
	repo := repository.NewMemory()
	library := usecase.New(repo)
	handler := delivery.New(library)
	mux := http.NewServeMux()
	mux.HandleFunc("POST /loans", handler.Lend)
	return mux
}

func main() {
	log.Fatal(http.ListenAndServe(":8080", delivery.Logging(newMux())))
}

/*
Вопрос: Назовите три слоя и что делает каждый.

Ответ:
Delivery разбирает HTTP-запрос и формирует ответ. Usecase проверяет правила
библиотеки и выполняет сценарий выдачи. Repository читает и сохраняет данные.
Entity содержит сущности и общие ошибки, а main соединяет реализации.
*/

/*
Вопрос: Три правила слоёв.

Ответ:
Вызовы идут только вниз: delivery → usecase → repository.
Через слой не перепрыгиваем: delivery не обращается к хранилищу напрямую.
Нижний слой не знает верхнего: usecase не знает HTTP и кодов ответа,
а repository не зависит от usecase или delivery.
*/

/*
Вопрос: Почему интерфейс repository объявляют в пакете usecase?

Ответ:
Usecase определяет, какие операции нужны его сценарию. Реализация хранилища
подходит под этот интерфейс неявно. Поэтому можно заменить память базой или
подделкой для теста, не меняя правила и не связывая usecase с конкретным repository.
*/

/*
Вопрос: Когда ответ 400, а когда 409?

Ответ:
400 возвращается при ошибке самого запроса: неверный JSON или отсутствует
обязательный идентификатор. 409 означает, что запрос разобран, но текущее
состояние мешает выдаче. Книга уже выдана, у читателя три книги на руках
или срок возврата одной из них истёк.
*/

/*
Вопрос: Что случится с `map`-хранилищем, если запустить 3 копии сервиса?

Ответ:
У каждой копии будет своя map. Они не увидят выдачи друг друга и смогут
выдать одну книгу разным читателям. Для согласованной работы нужно общее
хранилище с подходящим механизмом атомарности. При перезапуске данные map теряются.
*/

/*
Вопрос: Что поменяется, если запись к врачу добавят в Telegram-бота?

Ответ:
Добавится другой delivery: он разбирает сообщение бота, вызывает тот же
usecase и переводит результат или ошибку в ответ пользователю. Правила
записи и repository менять из-за нового способа ввода не требуется.
*/

/*
Вопрос: В исходном `homework/fat` один замок закрывает и проверки, и сохранение.
Что случится при двух одновременных запросах, если после разделения каждый
метод repository будет брать замок отдельно? Как не выдать одну книгу дважды?

Ответ:
Доступ к map защищён, но весь сценарий не атомарен. Оба запроса могут увидеть
свободную книгу, пройти проверку лимита и сохранить выдачу. Оба получат успех,
а последняя запись перезапишет первую. Так же можно превысить лимит читателя
при выдаче разных книг. Race detector не обязан обнаружить такую логическую гонку.

Проверки и сохранение нужно выполнять в одной согласованной операции:
например, в общей критической секции или транзакции с подходящей изоляцией.
При этом правила остаются в usecase, а механизм атомарности предоставляет
инфраструктура. В учебном решении сохранена показанная на лекции схема
с отдельными методами: она не гарантирует корректность одновременных выдач.
*/
